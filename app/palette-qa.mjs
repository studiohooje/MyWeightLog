import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {connect} from './qa-cdp.mjs';
import {emptyDB} from './domain.js';

const c=await connect(9238,'http://localhost:4173');
const run=expression=>c.run(expression);
const wait=async expression=>{for(let i=0;i<50;i++){if(await run(expression))return;await new Promise(r=>setTimeout(r,100))}throw Error('Timed out: '+expression)};
const click=selector=>run(`document.querySelector(${JSON.stringify(selector)}).click()`);
const fill=(selector,value)=>run(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}))})()`);
const shot=async name=>{const image=await c.send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});await fs.writeFile(`../artifacts/${name}.png`,Buffer.from(image.data,'base64'))};
try{
 await c.send('Page.enable');
 await c.send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await c.send('Emulation.setTouchEmulationEnabled',{enabled:true});
 await wait('!!document.querySelector(`[data-page="food"]`)');
 const seed=emptyDB();seed.foods=[{name:'현미밥',servingUnit:'g',servingQty:100,calories:165,carbs:35.6,protein:3.3,fat:1.2,source:'manual'}];
 await run(`localStorage.setItem('myweightlog.v1',${JSON.stringify(JSON.stringify(seed))})`);
 await c.send('Page.reload',{ignoreCache:true});
 await wait('!!document.querySelector(`[data-page="food"]`)');
 await click('[data-page="food"]');
 await click('[data-modal="batch"]');
 assert.equal(await run('document.querySelector(`.modal-backdrop`).classList.contains(`quick-palette`)'),true);
 const mealDims=await run('({viewport:innerWidth,scroll:document.documentElement.scrollWidth,sheet:Math.round(document.querySelector(`.sheet`).getBoundingClientRect().width),search:Math.round(document.querySelector(`#q-food-search`).getBoundingClientRect().top),choices:Math.round(document.querySelector(`.quick-choices`).getBoundingClientRect().top)})');
 assert.ok(mealDims.scroll<=mealDims.viewport,`Meal horizontal overflow ${JSON.stringify(mealDims)}`);
 assert.ok(mealDims.search<mealDims.choices+90,'Food search is not at top of choices');
 await shot('qa-quick-palette-meal');
 await fill('#q-food-search','현미밥');
 await wait('!!document.querySelector(`[data-q-food="현미밥|g"]`)');
 await click('[data-q-food="현미밥|g"]');
 assert.equal(await run('getComputedStyle(document.querySelector(`.quick-choices`)).display'),'none');
 assert.ok(await run('!!document.querySelector(`#q-qty`)'));
 await shot('qa-quick-palette-food-amount');
 await fill('#q-qty','210');
 await click('#q-confirm-food');
 await click('#q-save-meal');
 assert.equal(await run('JSON.parse(localStorage.getItem("myweightlog.v1")).meals.at(-1).servingQty'),210);
 await click('[data-page="workout"]');
 await click('[data-modal="workout"]');
 assert.equal(await run('document.querySelector(`.modal-backdrop`).classList.contains(`quick-palette`)'),true);
 const workoutDims=await run('({viewport:innerWidth,scroll:document.documentElement.scrollWidth,search:Math.round(document.querySelector(`#q-ex-search`).getBoundingClientRect().top),choices:Math.round(document.querySelector(`.quick-choices`).getBoundingClientRect().top)})');
 assert.ok(workoutDims.scroll<=workoutDims.viewport,`Workout horizontal overflow ${JSON.stringify(workoutDims)}`);
 assert.ok(workoutDims.search<workoutDims.choices+90,'Exercise search is not at top of choices');
 await fill('#q-ex-search','불가리안');
 await wait('!!document.querySelector(`[data-q-ex="exercise:불가리안 스플릿 스쿼트"]`)');
 await click('[data-q-ex="exercise:불가리안 스플릿 스쿼트"]');
 await shot('qa-quick-palette-workout');
 await click('#q-first-set');
 assert.equal(await run('getComputedStyle(document.querySelector(`.quick-choices`)).display'),'none');
 await shot('qa-quick-palette-set');
 await fill('#q-set-weight','5');
 await fill('#q-set-reps','10');
 await click('#q-save-set');
 assert.equal(await run('JSON.parse(localStorage.getItem("myweightlog.v1")).workouts.at(-1).exercises[0].sets[0].weight'),5);
 console.log('PASS quick palettes: 390px layout, search, food and set saving, no horizontal overflow');
}finally{c.close()}
